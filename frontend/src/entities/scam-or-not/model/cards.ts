export function getScamOrNotTopic(topicId: string) {
    return scamOrNotTopics.find((topic) => topic.id === topicId)
}

export function getScamOrNotTopicCards(topicId: string) {
    return scamOrNotCards.filter((card) => card.topicId === topicId)
}

export function hasScamOrNotTopic(topicId: string) {
    return scamOrNotCards.some((card) => card.topicId === topicId)
}

export function shuffleScamOrNotCards(cards: ScamOrNotCard[]) {
    const result = [...cards]

    for (let index = result.length - 1; index > 0; index -= 1) {
        const randomIndex = Math.floor(Math.random() * (index + 1))
        const current = result[index]

        result[index] = result[randomIndex]
        result[randomIndex] = current
    }

    return result
}

export function getMixedScamOrNotCards(limit = 10) {
    return shuffleScamOrNotCards(scamOrNotCards).slice(0, limit)
}
